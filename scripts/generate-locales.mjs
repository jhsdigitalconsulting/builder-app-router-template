/**
 * Writes packages/components/utils/enabled-locales.json from the locales enabled
 * in the Builder space (Space settings → Localization). The site serves exactly
 * these locales (plus the default). Runs before `pnpm dev` and `pnpm build`.
 *
 * The output file is gitignored (no merge conflicts). Fails open: with no key, a
 * network error, or an empty Builder list, it keeps the existing file (or creates
 * one listing no extra locales) and exits 0, so a Builder outage never breaks a build.
 * Read-only against Builder. The private key is never printed.
 */
import { GraphQLClient, gql } from "graphql-request";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, findCurrentApp } from "./lib/apps.mjs";

const APP = findCurrentApp();
const OUT = join(ROOT, "packages/components/utils/enabled-locales.json");

try {
  const raw = readFileSync(join(APP.path, ".env.local"), "utf8");
  for (const line of raw.split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "").trim();
  }
} catch {
  // use the existing environment
}

// The file is gitignored, so a fresh clone has none and localeUtils would fail to
// import it. Always leave a file behind: with nothing known yet, the site serves
// only the default locale.
function ensureFile() {
  try {
    readFileSync(OUT, "utf8");
  } catch {
    writeFileSync(
      OUT,
      JSON.stringify({ _comment: "Generated by scripts/generate-locales.mjs. Gitignored.", locales: [] }, null, 2) + "\n"
    );
  }
}
ensureFile();

const key = process.env.BUILDER_PRIVATE_KEY;
if (!key) {
  console.log("• generate-locales: no BUILDER_PRIVATE_KEY; keeping existing enabled-locales.json");
  process.exit(0);
}

try {
  const client = new GraphQLClient("https://cdn.builder.io/api/v2/admin", {
    headers: { Authorization: `Bearer ${key}` },
  });
  const { settings } = await client.request(gql`query { settings }`);
  const list = settings?.customTargetingAttributes?.locale?.enum;
  const locales = Array.isArray(list) ? list.filter((l) => typeof l === "string") : [];
  if (locales.length === 0) {
    console.log("• generate-locales: Builder lists no locales; keeping existing enabled-locales.json");
    process.exit(0);
  }
  const body =
    JSON.stringify(
      {
        _comment: "Generated from the Builder space by scripts/generate-locales.mjs. Gitignored; do not edit by hand.",
        locales,
      },
      null,
      2
    ) + "\n";
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch {}
  if (current !== body) writeFileSync(OUT, body);
  console.log(`• generate-locales: ${locales.length} locale(s) enabled in Builder: ${locales.join(", ")}${current !== body ? " (updated)" : ""}`);
} catch (err) {
  console.log(`• generate-locales: could not read Builder (${(err && err.message) || err}); keeping existing enabled-locales.json`);
}
